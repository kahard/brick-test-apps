"""Writes chime_wav.h: a short bell chime as a 16-bit mono WAV at 22.05 kHz
(two notes, a few decaying partials each), compiled into the audio test so
it plays a real WAV file from flash on every board.

    python make_chime.py
"""
import io
import math
import struct
import wave
from pathlib import Path

RATE = 22050
NOTES = [(0.00, 880.0), (0.18, 1318.5)]  # A5, then E6
PARTIALS = [(1.0, 1.0, 1.6), (2.0, 0.45, 2.6), (3.01, 0.22, 3.6), (4.2, 0.12, 5.0)]  # ratio, gain, decay per s
LENGTH_S = 1.1
PEAK = 0.7

frames = []
for index in range(int(RATE * LENGTH_S)):
    t = index / RATE
    value = 0.0
    for start, base in NOTES:
        if t < start:
            continue
        local = t - start
        attack = min(local / 0.004, 1.0)
        for ratio, gain, decay in PARTIALS:
            value += attack * gain * math.exp(-decay * local) * math.sin(2 * math.pi * base * ratio * local)
    frames.append(value)
scale = PEAK / max(abs(value) for value in frames)
pcm = b"".join(struct.pack("<h", int(round(value * scale * 32767))) for value in frames)

buffer = io.BytesIO()
with wave.open(buffer, "wb") as wav:
    wav.setnchannels(1)
    wav.setsampwidth(2)
    wav.setframerate(RATE)
    wav.writeframes(pcm)
data = buffer.getvalue()

lines = [
    "#pragma once",
    "",
    "// Generated by make_chime.py: a bell chime, 16-bit mono WAV at 22.05 kHz.",
    "",
    "#include <cstddef>",
    "#include <cstdint>",
    "",
    "#include \"brick/core/memory/ProgramMemory.h\"",
    "",
    "namespace audio_test",
    "{",
    "",
    f"inline constexpr std::size_t kChimeWavSize = {len(data)};",
    "",
    "alignas(4) inline const std::uint8_t kChimeWav[kChimeWavSize] BRICK_PROGMEM = {",
]
for offset in range(0, len(data), 16):
    lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in data[offset:offset + 16]) + ",")
lines += ["};", "", "}  // namespace audio_test", ""]
Path(__file__).with_name("chime_wav.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"chime_wav.h: {len(data)} bytes, {len(frames) / RATE:.2f} s")
