"""The Wi-Fi network compiled into the network test applications.

Taken from the environment variables BRICK_WIFI_SSID and BRICK_WIFI_PASSWORD,
otherwise from wifi-credentials.txt in the repository root (git-ignored),
with the lines

    SSID=MyNetwork
    PASSWORD=my password

Without either, the applications only open their hotspot. The values end up
in the firmware image in plain text; never commit them.
"""
from __future__ import annotations

import os
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[1]
CREDENTIALS_FILE = REPOSITORY / "wifi-credentials.txt"


def read_credentials() -> tuple[str, str]:
    ssid = os.environ.get("BRICK_WIFI_SSID")
    if ssid is not None:
        return ssid, os.environ.get("BRICK_WIFI_PASSWORD", "")
    if not CREDENTIALS_FILE.is_file():
        return "", ""
    values: dict[str, str] = {}
    for line in CREDENTIALS_FILE.read_text(encoding="utf-8").splitlines():
        key, separator, value = line.partition("=")
        if separator:
            values[key.strip().upper()] = value.strip()
    return values.get("SSID", ""), values.get("PASSWORD", "")


def c_string(text: str) -> str:
    """A C string literal; octal escapes, because hex ones swallow following digits."""
    out = []
    for byte in text.encode("utf-8"):
        character = chr(byte)
        if character in '"\\' or byte < 32 or byte > 126:
            out.append("\\%03o" % byte)
        else:
            out.append(character)
    return '"' + "".join(out) + '"'


def write_header(path: Path) -> str:
    """Writes the header when its content changes; returns the SSID (may be empty)."""
    ssid, password = read_credentials()
    if len(ssid.encode("utf-8")) > 32 or (password and not 8 <= len(password.encode("utf-8")) <= 63):
        raise SystemExit("wifi_credentials: the SSID has at most 32 bytes, a password 8 to 63")
    content = (
        "#pragma once\n"
        "// Generated by tools/wifi_credentials.py; never commit this file.\n"
        f"inline constexpr char kWifiSsid[]     = {c_string(ssid)};\n"
        f"inline constexpr char kWifiPassword[] = {c_string(password)};\n"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.is_file() or path.read_text(encoding="utf-8") != content:
        path.write_text(content, encoding="utf-8", newline="\n")
    return ssid
